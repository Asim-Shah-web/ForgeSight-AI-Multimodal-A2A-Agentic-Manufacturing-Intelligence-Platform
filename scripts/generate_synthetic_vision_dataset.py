"""
Generates a small, procedurally-created synthetic PCB-like image dataset in
YOLO format, for the sole purpose of exercising the CV inference pipeline
end-to-end (upload -> detect -> threshold -> persist -> API) in development
and tests.

This data contains NO real defect signal. Every image is a plain rectangular
"board" background with randomly placed rectangles/circles standing in for
components, and one randomly placed, visually distinct red-outlined marker
box standing in for exactly one of the 13 Phase 1/3 defect classes.

Usage:
    python scripts/generate_synthetic_vision_dataset.py --num-images 200 --val-split 0.2

Output:
    data/vision/synthetic_dataset/
        images/train/*.jpg
        images/val/*.jpg
        labels/train/*.txt   (YOLO format: class_idx cx cy w h, normalized 0-1)
        labels/val/*.txt
        data.yaml            (Ultralytics dataset config)
        README.md            (explicit synthetic-data disclosure)
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from forgesight.config.logging import get_logger
from forgesight.config.settings import settings

logger = get_logger(__name__)

IMAGE_SIZE = 640
BACKGROUND_COLOR = (40, 90, 50)  # PCB-green-ish background
COMPONENT_COLOR_RANGE = ((150, 150, 150), (210, 210, 210))
MARKER_COLOR = (220, 30, 30)  # visually distinct "defect marker" outline


def _random_color(low: tuple[int, int, int], high: tuple[int, int, int]) -> tuple[int, int, int]:
    return tuple(random.randint(low[i], high[i]) for i in range(3))  # type: ignore[return-value]


def _draw_background_components(draw: ImageDraw.ImageDraw, num_components: int) -> None:
    for _ in range(num_components):
        w, h = random.randint(20, 60), random.randint(10, 30)
        x = random.randint(10, IMAGE_SIZE - w - 10)
        y = random.randint(10, IMAGE_SIZE - h - 10)
        color = _random_color(*COMPONENT_COLOR_RANGE)
        if random.random() < 0.3:
            draw.ellipse([x, y, x + w, y + h], outline=color, width=2)
        else:
            draw.rectangle([x, y, x + w, y + h], outline=color, width=2)


def _draw_defect_marker(draw: ImageDraw.ImageDraw) -> tuple[int, int, int, int]:
    """Draws the single defect-marker box and returns its pixel bounding box
    as (x_min, y_min, x_max, y_max)."""
    w, h = random.randint(30, 70), random.randint(20, 50)
    x = random.randint(20, IMAGE_SIZE - w - 20)
    y = random.randint(20, IMAGE_SIZE - h - 20)
    draw.rectangle([x, y, x + w, y + h], outline=MARKER_COLOR, width=3)
    return x, y, x + w, y + h


def _to_yolo_format(box: tuple[int, int, int, int], image_size: int) -> tuple[float, float, float, float]:
    x_min, y_min, x_max, y_max = box
    cx = ((x_min + x_max) / 2) / image_size
    cy = ((y_min + y_max) / 2) / image_size
    w = (x_max - x_min) / image_size
    h = (y_max - y_min) / image_size
    return cx, cy, w, h


def _generate_one_image(index: int, defect_classes: list[str]) -> tuple[Image.Image, str]:
    image = Image.new("RGB", (IMAGE_SIZE, IMAGE_SIZE), color=BACKGROUND_COLOR)
    draw = ImageDraw.Draw(image)

    _draw_background_components(draw, num_components=random.randint(15, 30))

    class_idx = random.randint(0, len(defect_classes) - 1)
    box = _draw_defect_marker(draw)
    cx, cy, w, h = _to_yolo_format(box, IMAGE_SIZE)
    label_line = f"{class_idx} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n"

    return image, label_line


def generate_dataset(output_dir: Path, num_images: int, val_split: float, seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)

    defect_classes = settings.cv_defect_classes

    images_train_dir = output_dir / "images" / "train"
    images_val_dir = output_dir / "images" / "val"
    labels_train_dir = output_dir / "labels" / "train"
    labels_val_dir = output_dir / "labels" / "val"
    for directory in (images_train_dir, images_val_dir, labels_train_dir, labels_val_dir):
        directory.mkdir(parents=True, exist_ok=True)

    num_val = max(1, int(num_images * val_split))
    num_train = num_images - num_val

    for i in range(num_images):
        image, label_line = _generate_one_image(i, defect_classes)
        split = "val" if i < num_val else "train"
        images_dir = images_val_dir if split == "val" else images_train_dir
        labels_dir = labels_val_dir if split == "val" else labels_train_dir

        filename = f"synthetic_{i:05d}"
        image.save(images_dir / f"{filename}.jpg", quality=90)
        (labels_dir / f"{filename}.txt").write_text(label_line, encoding="utf-8")

    data_yaml_content = (
        f"# Auto-generated by scripts/generate_synthetic_vision_dataset.py\n"
        f"# SYNTHETIC PLACEHOLDER DATA - see README.md in this directory.\n"
        f"path: {output_dir.resolve()}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"nc: {len(defect_classes)}\n"
        f"names: {defect_classes}\n"
    )
    (output_dir / "data.yaml").write_text(data_yaml_content, encoding="utf-8")

    readme_content = f"""# Synthetic Vision Dataset — PLACEHOLDER DATA ONLY

**This dataset contains no real PCB defect signal.** Every image is a
procedurally generated background with random component-like shapes and
exactly one visually distinct red-outlined marker box standing in for a
randomly chosen defect class. It exists solely to exercise the ForgeSight
CV inference pipeline (load -> infer -> threshold -> persist -> API)
end-to-end during development and testing.

- Total images: {num_images} ({num_train} train / {num_val} val)
- Classes ({len(defect_classes)}): {", ".join(defect_classes)}
- Generated with seed: {seed}

**Do not use a model trained on this dataset for any real quality decision.**
Any `CvFinding` produced by such a model must carry
`dataset_used_for_training = "{settings.cv_dataset_used_for_training}"` per
`config/vision/vision.yaml`, so downstream consumers can never mistake its
output for a validated production detector.

A real, labeled manufacturing defect dataset is required before this model
can be used for anything beyond pipeline testing.
"""
    (output_dir / "README.md").write_text(readme_content, encoding="utf-8")

    logger.info(
        "synthetic_vision_dataset_generated",
        extra={"output_dir": str(output_dir), "num_train": num_train, "num_val": num_val},
    )
    print(f"Generated {num_images} synthetic images ({num_train} train / {num_val} val) at {output_dir}")
    print(f"Ultralytics data config written to {output_dir / 'data.yaml'}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate synthetic ForgeSight vision dataset.")
    parser.add_argument("--num-images", type=int, default=200)
    parser.add_argument("--val-split", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/vision/synthetic_dataset",
    )
    args = parser.parse_args()

    generate_dataset(
        output_dir=Path(args.output_dir),
        num_images=args.num_images,
        val_split=args.val_split,
        seed=args.seed,
    )


if __name__ == "__main__":
    main()